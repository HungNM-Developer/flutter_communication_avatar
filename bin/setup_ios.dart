import 'dart:io';

/// CLI Setup Script for automated iOS configuration of flutter_communication_avatar.
///
/// Usage:
///   dart run flutter_communication_avatar:setup_ios [--check | --apply | --extension | --help]
void main(List<String> args) async {
  final hasHelp = args.contains('--help') || args.contains('-h');
  final hasCheck = args.contains('--check');
  final hasApply = args.contains('--apply');
  final hasExtension = args.contains('--extension');

  stdout.writeln('======================================================');
  stdout.writeln(' 🚀 flutter_communication_avatar iOS Setup CLI');
  stdout.writeln('======================================================\n');

  if (hasHelp || args.isEmpty) {
    printHelp();
    return;
  }

  final currentDir = Directory.current;
  final plistFile = File('${currentDir.path}/ios/Runner/Info.plist');
  final pbxprojFile = File('${currentDir.path}/ios/Runner.xcodeproj/project.pbxproj');

  if (!plistFile.existsSync()) {
    stderr.writeln('❌ Error: Could not locate ios/Runner/Info.plist.');
    stderr.writeln('   Make sure you are running this script inside your Flutter project root directory.');
    exit(1);
  }

  if (hasCheck) {
    checkIosConfiguration(plistFile, pbxprojFile);
  } else if (hasApply) {
    applyIosConfiguration(plistFile);
  }

  if (hasExtension) {
    generateExtensionTemplate(currentDir);
  }
}

void printHelp() {
  stdout.writeln('''
Automates iOS setup for flutter_communication_avatar communication notifications.

USAGE:
  dart run flutter_communication_avatar:setup_ios [COMMAND]

COMMANDS:
  --check      Inspects ios/Runner/Info.plist for INSendMessageIntent activity entitlement.
  --apply      Automatically injects INSendMessageIntent into ios/Runner/Info.plist.
  --extension  Generates starter NotificationService.swift code for iOS Notification Service Extension.
  --help, -h   Show this help message.

EXAMPLES:
  # Check your current iOS project status:
  dart run flutter_communication_avatar:setup_ios --check

  # Automatically configure Info.plist and generate extension boilerplate:
  dart run flutter_communication_avatar:setup_ios --apply --extension
''');
}

void checkIosConfiguration(File plistFile, File pbxprojFile) {
  stdout.writeln('🔍 Checking iOS Configuration in ${plistFile.path}...\n');

  final plistContent = plistFile.readAsStringSync();

  final hasIntent = plistContent.contains('INSendMessageIntent');

  if (hasIntent) {
    stdout.writeln('  [✓] NSUserActivityTypes contains INSendMessageIntent');
  } else {
    stdout.writeln('  [!] NSUserActivityTypes is MISSING INSendMessageIntent');
    stdout.writeln('      Run with --apply to automatically add it to Info.plist.');
  }

  if (pbxprojFile.existsSync()) {
    final pbxContent = pbxprojFile.readAsStringSync();
    if (pbxContent.contains('com.apple.InAppPurchase') || pbxContent.contains('Siri')) {
      stdout.writeln('  [✓] Xcode project references Capabilities.');
    }
  }

  stdout.writeln('\n🎉 iOS Check complete.');
}

void applyIosConfiguration(File plistFile) {
  stdout.writeln('🛠️ Applying iOS configuration changes to ${plistFile.path}...\n');

  var content = plistFile.readAsStringSync();

  if (content.contains('INSendMessageIntent')) {
    stdout.writeln('  [✓] Info.plist already contains INSendMessageIntent. No changes needed.');
    return;
  }

  // Check if NSUserActivityTypes array exists
  if (content.contains('<key>NSUserActivityTypes</key>')) {
    final target = '<key>NSUserActivityTypes</key>';
    final replacement = '''<key>NSUserActivityTypes</key>
\t<array>
\t\t<string>INSendMessageIntent</string>''';

    content = content.replaceFirst(target, replacement);
  } else {
    // Inject key-array before closing </dict>
    final lastDictIndex = content.lastIndexOf('</dict>');
    if (lastDictIndex != -1) {
      final injection = '''\t<key>NSUserActivityTypes</key>
\t<array>
\t\t<string>INSendMessageIntent</string>
\t</array>
''';
      content = content.substring(0, lastDictIndex) + injection + content.substring(lastDictIndex);
    }
  }

  plistFile.writeAsStringSync(content);
  stdout.writeln('  [✓] Successfully updated Info.plist with INSendMessageIntent key!');
}

void generateExtensionTemplate(Directory currentDir) {
  final extDir = Directory('${currentDir.path}/ios/NotificationServiceExtension');
  if (!extDir.existsSync()) {
    extDir.createSync(recursive: true);
  }

  final extFile = File('${extDir.path}/NotificationService.swift');
  const extensionCode = '''//
// NotificationService.swift
// Generated by flutter_communication_avatar CLI
//

import UserNotifications
import Intents
import flutter_communication_avatar

class NotificationService: UNNotificationServiceExtension {

    var contentHandler: ((UNNotificationContent) -> Void)?
    var bestAttemptContent: UNMutableNotificationContent?

    override func didReceive(_ request: UNNotificationRequest, withContentHandler contentHandler: @escaping (UNNotificationContent) -> Void) {
        self.contentHandler = contentHandler
        self.bestAttemptContent = (request.content.mutableCopy() as? UNMutableNotificationContent)

        // Process communication avatar intent for remote push notifications
        CommunicationAvatarExtensionHelper.processNotificationRequest(request) { finalContent in
            contentHandler(finalContent)
        }
    }

    override func serviceExtensionTimeWillExpire() {
        if let contentHandler = contentHandler, let bestAttemptContent = bestAttemptContent {
            contentHandler(bestAttemptContent)
        }
    }
}
''';

  extFile.writeAsStringSync(extensionCode);
  stdout.writeln('\n📱 Generated iOS Notification Service Extension starter file:');
  stdout.writeln('   Location: ${extFile.path}');
  stdout.writeln('\n💡 Next steps in Xcode:');
  stdout.writeln('   1. Open ios/Runner.xcworkspace in Xcode.');
  stdout.writeln('   2. Select File -> New -> Target -> Notification Service Extension.');
  stdout.writeln('   3. Replace the created NotificationService.swift with the generated file.');
}
